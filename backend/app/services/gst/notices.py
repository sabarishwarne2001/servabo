"""GST Credit's in-app notices and the Monday digest (Final session 1, 3A).

The owner should hear about GST credit without opening the page. Four notices, all in the "GST credit" category (on by default;
audience: owners, admins and the billing role), and one weekly email:

  import     a GSTR-2B was imported (INFO; in the app only)                       emitted where the import finishes
  window     invoices reached 150 days unpaid: 30 days left of the 180-day rule  (WARNING; also emailed)   daily sweep
  supplier   the 14th has passed and suppliers still have not reported invoices  (WARNING; also emailed)   daily sweep
  ims        records are waiting for an IMS action before GSTR-3B (the 20th)      (INFO; full-access plans only)
  digest     Monday 09:00 in the workspace's zone: the figures, one email, only when there is something to say

Plan awareness: the headline figures are on every plan, so every notice carries only counts and rupees. The IMS notice names a
list that is the paid part, so it is sent only where the lists are open. The digest says what the lists would add where they are not.

ONCE. `gst_notice_sends` holds one row per organization, kind and key; the insert is the claim, so two workers or a retried job never
say a thing twice. The sweeps skip archived, suspended and unpaid organizations and the invented sample company.
"""

from __future__ import annotations

import logging
import uuid
from datetime import date, datetime, timedelta, timezone
from typing import Any, Optional
from zoneinfo import ZoneInfo

from sqlalchemy import func, select
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.orm import Session

from app.core.display_format import format_amount_micros
from app.models.gst import GstMatch, GstNoticeSend, GstReturn
from app.models.notification import NotificationPriority, NotificationType
from app.models.organization import Organization, OrganizationRole, OrganizationStatus
from app.models.workspace import Workspace
from app.services.gst import vocabulary as v

logger = logging.getLogger("app.services.gst.notices")

KIND_IMPORT, KIND_WINDOW, KIND_SUPPLIER, KIND_IMS, KIND_DIGEST = "import", "window", "supplier", "ims", "digest"

#: Who hears about GST credit: the people who act on it and the one who pays for it.
GST_ROLES: tuple[OrganizationRole, ...] = (OrganizationRole.OWNER, OrganizationRole.ADMIN, OrganizationRole.BILLING)
#: GSTR-2B for the month before is generated by the 14th; GSTR-3B is due on the 20th (monthly filers).
SUPPLIER_DAY = 14
FILING_DAY = 20
DIGEST_HOUR = 9
MONTH_NAMES = ("January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
               "November", "December")


def claim(db: Session, organization_id: uuid.UUID, kind: str, key: str) -> bool:
    """True when this call is the one that gets to say it (the insert found no row)."""
    inserted = db.execute(
        pg_insert(GstNoticeSend).values(organization_id=organization_id, kind=kind, key=key)
        .on_conflict_do_nothing(index_elements=["organization_id", "kind", "key"]).returning(GstNoticeSend.key)).first()
    return inserted is not None


def _count_recipients(db: Session, organization_id: uuid.UUID, kind: str, key: str, people: int) -> None:
    row = db.get(GstNoticeSend, (organization_id, kind, key))
    if row is not None:
        row.recipients = people


def period_words(period: str) -> str:
    """"2026-09" -> "September 2026"."""
    year, month = period.split("-")
    return f"{MONTH_NAMES[int(month) - 1]} {year}"


def zone_of(db: Session, organization_id: uuid.UUID) -> ZoneInfo:
    """The zone of the organization's oldest workspace (organizations have no clock of their own, N-064)."""
    workspace = db.execute(select(Workspace).where(
        Workspace.organization_id == organization_id, Workspace.is_sample.is_(False)).order_by(Workspace.created_at)
    ).scalars().first()
    try:
        return ZoneInfo(workspace.timezone if workspace and workspace.timezone else "UTC")
    except Exception:  # noqa: BLE001 - a zone that cannot be read falls back to UTC rather than never sending
        return ZoneInfo("UTC")


def workspace_ids(db: Session, organization_id: uuid.UUID) -> list[uuid.UUID]:
    from app.services.gst import org as gst_org

    return [w.id for w in gst_org.workspaces_of(db, organization_id)]


def full_access(db: Session, organization_id: uuid.UUID) -> bool:
    """Whether this organization's plan (or add-on) opens the GST lists. The sample company is never asked."""
    from app.services.gst import gate

    workspaces = _workspaces(db, organization_id)
    return bool(workspaces) and gate.full_access(db, workspaces[0])


def _workspaces(db: Session, organization_id: uuid.UUID) -> list[Workspace]:
    from app.services.gst import org as gst_org

    return gst_org.workspaces_of(db, organization_id)


def figures_of(db: Session, organization_id: uuid.UUID, *, today: Optional[date] = None) -> dict[str, dict[str, int]]:
    """The six headline figures summed over the organization's own workspaces: {key: {amount_micros, count, suppliers?}}."""
    from app.services.gst import summary

    ids = workspace_ids(db, organization_id)
    if not ids:
        return {}
    return {f["key"]: f for f in summary.figures(db, workspace_ids=ids, today=today)["figures"]}


def money(micros: int) -> str:
    return format_amount_micros(micros, "INR")


def _tell(db: Session, organization_id: uuid.UUID, *, title: str, message: str, priority: NotificationPriority) -> int:
    from app.services import notification_preferences_service as prefs
    from app.services import organization_notification_service as notices

    return notices.emit_to_roles(
        db, organization_id=organization_id, roles=GST_ROLES, title=title, message=message,
        notification_type=NotificationType.SYSTEM, priority=priority, category=prefs.GST_CREDIT, action="gst")


# ------------------------------------------------------------------------------------------------ import finished

def import_finished(db: Session, *, workspace: Workspace, return_id: uuid.UUID, gstin: str, period: str, records: int) -> bool:
    """Tell the owners a GSTR-2B went in, with the headline. Never raises into the import."""
    if workspace.is_sample:
        return False
    try:
        with db.begin_nested():
            if not claim(db, workspace.organization_id, KIND_IMPORT, str(return_id)):
                return False
            fig = figures_of(db, workspace.organization_id)
            parts = [f"{records:,} supplier records for {period_words(period)} (GSTIN {gstin}) were imported into {workspace.workspace_name}."]
            if fig and fig["claimable_now"]["amount_micros"]:
                parts.append(f"Credit claimable now: {money(fig['claimable_now']['amount_micros'])}.")
            waiting = fig.get("waiting") if fig else None
            if waiting and waiting["count"]:
                parts.append(f"{waiting['count']} of your invoices are waiting for {waiting.get('suppliers', 0)} supplier(s) to report them.")
            people = _tell(db, workspace.organization_id, title="GSTR-2B imported", message=" ".join(parts),
                           priority=NotificationPriority.INFO)
            _count_recipients(db, workspace.organization_id, KIND_IMPORT, str(return_id), people)
        return True
    except Exception:  # noqa: BLE001 - a notice must never fail an import
        logger.warning("gst.notice_failed", extra={"kind": KIND_IMPORT}, exc_info=True)
        return False


# ------------------------------------------------------------------------------------------------ the daily sweeps

def window_notice(db: Session, organization_id: uuid.UUID, *, today: date) -> int:
    """Invoices that reached 150 days unpaid and were not yet announced: one notice for the lot. Returns how many invoices."""
    from sqlalchemy import Boolean, Date, and_, cast

    ids = workspace_ids(db, organization_id)
    if not ids:
        return 0
    cutoff = today - timedelta(days=v.RISK_NEAR_DAYS)
    rows = db.execute(select(GstMatch.id, GstMatch.tax_micros).where(
        GstMatch.workspace_id.in_(ids), GstMatch.risk.isnot(None), GstMatch.work_item_id.isnot(None),
        and_(cast(GstMatch.risk["paid"].astext, Boolean).is_(False), cast(GstMatch.risk["invoice_date"].astext, Date) <= cutoff))
        .order_by(GstMatch.id)).all()
    fresh = [(match_id, tax) for match_id, tax in rows if claim(db, organization_id, KIND_WINDOW, str(match_id))]
    if not fresh:
        return 0
    tax = sum(int(t or 0) for _id, t in fresh)
    n = len(fresh)
    message = (f"{n} invoice{' has' if n == 1 else 's have'} reached 150 days without a recorded payment"
               f"{f', with {money(tax)} of tax' if tax else ''}. If the supplier is not paid within 180 days of the invoice date, "
               "the credit may have to be reversed with interest. Record the payment, or ask your accountant.")
    people = _tell(db, organization_id, title=f"{n} invoice{'s' if n != 1 else ''} near the 180-day limit", message=message,
                   priority=NotificationPriority.WARNING)
    for match_id, _tax in fresh[:1]:
        _count_recipients(db, organization_id, KIND_WINDOW, str(match_id), people)
    return n


def _previous_period(day: date) -> str:
    month = day.month - 1 or 12
    year = day.year if day.month > 1 else day.year - 1
    return f"{year:04d}-{month:02d}"


def supplier_notice(db: Session, organization_id: uuid.UUID, *, today: date) -> int:
    """From the 14th: suppliers that have not reported invoices the books hold, for a month whose GSTR-2B is imported."""
    if today.day < SUPPLIER_DAY:
        return 0
    period = _previous_period(today)
    ids = workspace_ids(db, organization_id)
    if not ids or db.execute(select(func.count()).select_from(GstReturn).where(
            GstReturn.workspace_id.in_(ids), GstReturn.status == v.RETURN_ACTIVE, GstReturn.period == period)).scalar_one() == 0:
        return 0
    waiting = figures_of(db, organization_id, today=today).get("waiting")
    if not waiting or not waiting["count"]:
        return 0
    key = f"{today.year:04d}-{today.month:02d}"
    if not claim(db, organization_id, KIND_SUPPLIER, key):
        return 0
    suppliers = waiting.get("suppliers", 0)
    message = (f"GSTR-2B for {period_words(period)} is out. {suppliers} supplier{' has' if suppliers == 1 else 's have'} not reported "
               f"{waiting['count']} of your invoice{'s' if waiting['count'] != 1 else ''}, worth {money(waiting['amount_micros'])} of credit "
               "you cannot claim until they do. Ask them to report the invoices, and consider holding their payment.")
    people = _tell(db, organization_id, title=f"{suppliers} supplier{'s' if suppliers != 1 else ''} have not reported your invoices",
                   message=message, priority=NotificationPriority.WARNING)
    _count_recipients(db, organization_id, KIND_SUPPLIER, key, people)
    return waiting["count"]


def ims_notice(db: Session, organization_id: uuid.UUID, *, today: date) -> int:
    """From the 14th to the 20th, where the lists are open: records with a recommended IMS action nobody has decided yet."""
    if not (SUPPLIER_DAY <= today.day <= FILING_DAY) or not full_access(db, organization_id):
        return 0
    ids = workspace_ids(db, organization_id)
    if not ids:
        return 0
    pending = db.execute(select(func.count()).select_from(GstMatch).where(
        GstMatch.workspace_id.in_(ids), GstMatch.record_id.isnot(None), GstMatch.ims_action.isnot(None),
        GstMatch.decision.is_(None), GstMatch.status.notin_((v.NOT_ELIGIBLE, v.REVERSE_CHARGE)))).scalar_one()
    if not pending:
        return 0
    key = f"{today.year:04d}-{today.month:02d}"
    if not claim(db, organization_id, KIND_IMS, key):
        return 0
    message = (f"{pending} supplier record{'s are' if pending != 1 else ' is'} waiting for an Invoice Management System action on the "
               f"portal before you file GSTR-3B (due on the {FILING_DAY}th). Servabo recommends Accept, Pending or Reject for each; "
               "you act on the portal.")
    people = _tell(db, organization_id, title=f"{pending} IMS action{'s' if pending != 1 else ''} pending", message=message,
                   priority=NotificationPriority.INFO)
    _count_recipients(db, organization_id, KIND_IMS, key, people)
    return int(pending)


def organizations_with_returns(db: Session) -> list[uuid.UUID]:
    """Active organizations with an imported GSTR-2B in one of their own workspaces."""
    return list(db.execute(
        select(Organization.id).join(GstReturn, GstReturn.organization_id == Organization.id)
        .join(Workspace, Workspace.id == GstReturn.workspace_id)
        .where(Organization.status == OrganizationStatus.ACTIVE, GstReturn.status == v.RETURN_ACTIVE, Workspace.is_sample.is_(False))
        .group_by(Organization.id, Organization.created_at).order_by(Organization.created_at, Organization.id)).scalars())


def run_notices(db: Session, *, now: Optional[datetime] = None) -> dict[str, int]:
    """The daily sweeps for every organization that should hear. Commits per organization."""
    from app.workers.tenant_gate import inactive_reason, unpaid_reason

    moment = now or datetime.now(timezone.utc)
    totals = {"organizations": 0, "window": 0, "supplier": 0, "ims": 0}
    for organization_id in organizations_with_returns(db):
        if inactive_reason(db, organization_id=organization_id) or unpaid_reason(db, organization_id=organization_id):
            continue
        today = moment.astimezone(zone_of(db, organization_id)).date()
        try:
            totals["window"] += window_notice(db, organization_id, today=today)
            totals["supplier"] += supplier_notice(db, organization_id, today=today)
            totals["ims"] += ims_notice(db, organization_id, today=today)
            db.commit()
            totals["organizations"] += 1
        except Exception:  # noqa: BLE001 - one organization failing must not stop the others
            db.rollback()
            logger.warning("gst.notices_failed", extra={"organization_id": str(organization_id)}, exc_info=True)
    return totals


def handle_notices(payload: dict[str, Any]) -> dict[str, Any]:
    from app.db import session as session_module

    with session_module.SessionLocal() as db:
        return run_notices(db, now=payload_now(payload))


def payload_now(payload: dict[str, Any]) -> Optional[datetime]:
    """The clock a test sets (`now`, ISO 8601 with an offset). Honoured only outside production: a job payload must never
    be able to move a real organization's clock."""
    from app.core.config import settings

    raw = payload.get("now") if isinstance(payload, dict) else None
    if not raw or settings.ENVIRONMENT.lower() == "production":
        return None
    moment = datetime.fromisoformat(str(raw))
    return moment if moment.tzinfo else moment.replace(tzinfo=timezone.utc)


